/**
 * "AI in your product": the ready-made AI features an equipe team adds to the product it builds, on /features/ai/ and in
 * small placements (home day-one section, pricing page, header Resources menu, footer).
 *
 * Only claim what ships. Source of truth: equipe-cloud docs/product-ai.md and the public reference at ai.equipe.im/docs.
 * Public facts only: the fee (provider list price + 10%), the default monthly limit ($10), the note at 80%, the friendly
 * pause, limits per product/user/visitor (no numbers), per-product server-side keys stored as a hash, browser calls
 * refused, instructions kept on equipe's side, no prompts or answers stored. No model or provider names, no internal
 * limits, no key formats. Headlines say the outcome in plain words.
 */
import type { LocaleCode } from '../i18n';

/** The 11 ready-made features, grouped by where they live. Keys match the recipe ids in equipe-cloud (platform/src/product-ai-recipes.js). */
export const AI_GROUPS = {
  site: ['support', 'faq', 'translate', 'autofill', 'recommend'],
  admin: ['reviews', 'describe', 'reply', 'image'],
  server: ['leads', 'moderation'],
} as const;
export type AiGroup = keyof typeof AI_GROUPS;
export type AiFeature = (typeof AI_GROUPS)[AiGroup][number];
export const AI_FEATURES = [...AI_GROUPS.site, ...AI_GROUPS.admin, ...AI_GROUPS.server] as AiFeature[];

interface Item { title: string; text: string }
interface QA { question: string; answer: string }

/**
 * Words drawn inside each feature's small illustration. Example content (a bakery, a travel agency, a café) in the
 * page's language; product names and prices may stay as they are.
 */
export interface AiVis {
  support: { q: string; a: string };
  faq: { q: string; a: string; from: string };
  translate: { from: string; lang: string; to: string };
  autofill: { pasted: string; fields: [string, string][] };
  recommend: { q: string; items: [string, string][] };
  reviews: { count: string; lines: string[] };
  describe: { notes: string; out: string; use: string };
  reply: { incoming: string; draft: string; use: string };
  image: { prompt: string; use: string };
  /** The first inquiry (marked hot) and two more, marked warm and cold. */
  leads: { msg: string; tag: string; next: string; more: [[string, string], [string, string]] };
  moderation: { rows: [string, string][]; };
}

export interface AiCopy {
  /** Header Resources menu and footer. */
  nav: string; navDesc: string;
  page: { title: string; desc: string; h1: string; lead: string; ogAlt: string };
  /** The quotable answer at the top of the page (also the start of llms.txt's section). */
  answerLabel: string; answer: string;
  ctaStart: string; ctaHow: string;
  featuresTitle: string; featuresSub: string; illuNote: string;
  groups: Record<AiGroup, Item>;
  features: Record<AiFeature, Item>;
  vis: AiVis;
  how: { title: string; ask: string; askLabel: string; steps: [Item, Item, Item, Item]; note: string; shotAlt: string; shotCaption: string };
  pricing: { title: string; lead: string; points: [Item, Item, Item]; models: string; panelAlt: string; panelCaption: string };
  security: { title: string; lead: string; items: [Item, Item, Item, Item, Item, Item] };
  later: { title: string; text: string; items: [string, string, string] };
  dev: { title: string; text: string; link: string };
  faqTitle: string; faq: QA[];
  cta: { title: string; text: string; pricing: string };
  /** Small placements elsewhere on the site. */
  home: { title: string; text: string; link: string };
  pricingNote: { title: string; text: string; link: string };
}

